"""Installed Python CycloneDX inventory; optional fixed-host PyPI advisory snapshot.

Does not inspect environment variables, credentials, direct URLs or private paths.
PyPI advisories are not a complete native/OS vulnerability scan or license audit.
"""
import argparse
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime, timezone
import importlib.metadata
import json
from pathlib import Path
import re
import platform
import sys
from urllib.parse import quote
from urllib.request import urlopen


def normalized(name):
    return re.sub(r'[-_.]+','-',name).lower()


def component(distribution):
    name=normalized(distribution.metadata['Name']);version=distribution.version
    reference=f'pkg:pypi/{quote(name,safe="")}@{quote(version,safe="")}'
    declared=distribution.metadata.get('License-Expression') or distribution.metadata.get('License')
    if not declared or len(declared)>160 or '\n' in declared:
        classifiers=distribution.metadata.get_all('Classifier',[])
        declared=next((c.split(' :: ')[-1] for c in classifiers if c.startswith('License :: ')),None)
    item={'type':'library','bom-ref':reference,'name':name,'version':version,'purl':reference}
    if declared and declared.lower()!='unknown':item['licenses']=[{'license':{'name':declared}}]
    else:item['properties']=[{'name':'camera-monitoring:license-review','value':'metadata missing; manual review required'}]
    return item


def pypi_review(item):
    url=f'https://pypi.org/pypi/{quote(item["name"],safe="")}/{quote(item["version"],safe="")}/json'
    try:
        with urlopen(url,timeout=20) as response:
            raw=response.read(4*1024*1024+1)
        if len(raw)>4*1024*1024:raise ValueError('response budget')
        body=json.loads(raw)
        if normalized(body['info']['name'])!=item['name'] or body['info']['version']!=item['version']:
            raise ValueError('metadata identity mismatch')
        from packaging.tags import sys_tags
        from packaging.utils import parse_wheel_filename
        tags={tag:i for i,tag in enumerate(sys_tags())};wheels=[]
        for file in body.get('urls',[]):
            if file.get('packagetype')!='bdist_wheel' or file.get('yanked'):continue
            _,_,_,wheel_tags=parse_wheel_filename(file['filename'])
            priority=min((tags[t] for t in wheel_tags if t in tags),default=None)
            if priority is not None:wheels.append((priority,file))
        wheel=min(wheels,key=lambda pair:pair[0])[1] if wheels else None
        return {'name':item['name'],'version':item['version'],'source':url,
                'vulnerabilities':body.get('vulnerabilities',[]),'error':None,
                'wheel':{k:wheel[k] for k in ('filename','url','digests','size')} if wheel else None}
    except Exception:
        return {'name':item['name'],'version':item['version'],'source':url,
                'vulnerabilities':[],'error':'metadata lookup failed; review incomplete','wheel':None}


def lock_text(reviews):
    if any(r.get('error') or r.get('vulnerabilities') or not r.get('wheel') for r in reviews):
        raise ValueError('cannot lock an incomplete or vulnerable inventory')
    lines=['# Reviewed installed snapshot; Python 3.12 Linux x86_64 wheels only.',
           '# Generated by backend/scripts/release_inventory.py --pypi; no installed-byte integrity claim.']
    for row in sorted(reviews,key=lambda r:r['name']):
        if row['name'] in ('pip','setuptools','wheel'):continue
        digest=row['wheel']['digests']['sha256']
        if not re.fullmatch('[a-f0-9]{64}',digest):raise ValueError('invalid published wheel hash')
        lines.append(f"{row['name']}=={row['version']} --hash=sha256:{digest}")
    return '\n'.join(lines)+'\n'


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output',required=True);parser.add_argument('--pypi',action='store_true')
    parser.add_argument('--lock',help='optional reviewed platform-specific lock; requires successful --pypi')
    args=parser.parse_args()
    if args.lock and not args.pypi:parser.error('--lock requires --pypi')
    if args.lock and (sys.version_info[:2]!=(3,12) or sys.platform!='linux' or platform.machine()!='x86_64'):
        parser.error('reviewed lock target requires Python3.12 Linux x86_64')
    items=sorted([component(d) for d in importlib.metadata.distributions()],key=lambda c:c['name'])
    output=Path(args.output);output.mkdir(parents=True,exist_ok=True)
    bom={'bomFormat':'CycloneDX','specVersion':'1.6','version':1,
         'metadata':{'timestamp':datetime.now(timezone.utc).isoformat()},'components':items}
    (output/'python.cdx.json').write_text(json.dumps(bom,indent=2)+'\n')
    reviews=[]
    if args.pypi:
        with ThreadPoolExecutor(max_workers=4) as pool:reviews=list(pool.map(pypi_review,items))
    report={'generated_at':datetime.now(timezone.utc).isoformat(),'scope':'installed Python distributions only; excludes OS, Android, native bundled libraries and model weights',
            'advisory_source':'PyPI per-version JSON' if args.pypi else 'NOT EXECUTED',
            'packages':len(items),'lookup_errors':sum(bool(r.get('error')) for r in reviews),
            'affected_packages':sum(bool(r.get('vulnerabilities')) for r in reviews),'reviews':reviews,
            'limits':'Metadata license declarations need legal review; an empty advisory list does not prove absence of vulnerabilities. Published wheel hashes do not verify installed bytes.'}
    (output/'review.json').write_text(json.dumps(report,indent=2)+'\n')
    if args.lock:
        try:Path(args.lock).write_text(lock_text(reviews))
        except ValueError:
            print('Lock withheld: incomplete/vulnerable inventory or missing compatible wheel');return 1
    print(json.dumps({k:report[k] for k in ('packages','lookup_errors','affected_packages','advisory_source')}))
    return 1 if report['lookup_errors'] or report['affected_packages'] else 0

if __name__=='__main__':raise SystemExit(main())
